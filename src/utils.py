def is_ilegal(sudoku):
    memo_ = create_memo(sudoku)

    for val in memo_.values():
        if(len(val) == 0):
            return True
    return False

def count_zero(sudoku):
    zero_count = 0
    for row in sudoku:
        for num in row:
            if(num == 0):
                zero_count += 1
    return zero_count

def create_memo(sudoku,leng=0):
    memo = {}
    before = [i for i in range(1,10)]
    #空いてるマスを探す
    for row in range(9):
        for column in range(9):
            used = [] #縦、横、ボックスで埋まる候補にならないものリスト
            if(sudoku[row][column] == 0):

                #着目した空きセルと同じ行で使われてる数字をリストに追加
                for l_column in range(9):
                    if(sudoku[row][l_column] != 0 and not sudoku[row][l_column] in used):
                        used.append(sudoku[row][l_column])

                #着目した空きセルと同じ列で使われてる数字をリストに追加 
                for l_row in range(9):
                    if(sudoku[l_row][column] != 0 and not sudoku[l_row][column] in used):
                        used.append(sudoku[l_row][column])

                #着目した空きセルと同じボックスで使われてる数字をリストに追加
                for m_row in range((row // 3) * 3, ((row // 3) * 3) + 3):
                    for m_column in range((column // 3) * 3, ((column // 3) * 3) + 3):
                        if(sudoku[m_row][m_column] != 0 and not sudoku[m_row][m_column] in used):
                            used.append(sudoku[m_row][m_column])
                
                #memoに加える
                if(leng == 0):
                    memo[(row,column)] = ([i for i in before if i not in used])
                elif(leng == 2):
                    if(len([i for i in before if i not in used]) == 2):
                        memo[(row,column)] = ([i for i in before if i not in used])
                elif(leng == 3):
                    if(len([i for i in before if i not in used]) == 3):
                        memo[(row,column)] = ([i for i in before if i not in used])
    return memo

def get_units(type=None):
    units = []


    # 行
    row = []
    for r in range(9):
        units.append([(r, c) for c in range(9)])
        row.append(([(r, c) for c in range(9)]))
    


    # 列
    col = []
    for c in range(9):
        units.append([(r, c) for r in range(9)])
        col.append([(r, c) for r in range(9)])


    # ボックス
    boxe = []
    for br in range(3):
        for bc in range(3):
            box = [(r, c) for r in range(br*3, br*3+3) 
                           for c in range(bc*3, bc*3+3)]
            units.append(box)
            boxe.append(box)


    if(type == "row"):
        return row
    if(type == "col"):
        return col
    if(type == "box"):
        return boxe

    return units

def get_cell_units(pos,type=None):

    units = set()
    row, col = pos

    # 行ユニット
    row_unit = [(row, c) for c in range(9)]
    if(type == "row"):
        return row_unit
    units.update(row_unit)

    # 列ユニット
    col_unit = [(r, col) for r in range(9)]
    if(type == "col"):
        return col_unit
    units.update(col_unit)

    # ボックスユニット
    br, bc = row // 3, col // 3
    box_unit = [(r, c) for r in range(br*3, br*3+3)
                         for c in range(bc*3, bc*3+3)]
    if(type == "box"):
        return box_unit
    units.update(box_unit)

    units.discard(pos)

    if(type is None):
        return units


def import_sudoku_text(filename): #テキストファイルから数独データを取得
    with open(filename) as file:
        sudoku_raw = []
        current_line = []
        for line in file:
            new_line=line.rstrip("\n")
            for x in new_line:
                if x == " " or x == ".":
                    x = 0
                    current_line.append(x)
                else:
                    x = int(x)
                    current_line.append(x)
            sudoku_raw.append(current_line)
            current_line=[]
    return sudoku_raw

